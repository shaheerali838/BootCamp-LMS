import { body } from "express-validator";

const createReportValidation = [
  body("reportType")
    .trim()
    .notEmpty()
    .withMessage("Report type is required")
    .isLength({ min: 3, max: 100 })
    .withMessage("Report type must be between 3 and 100 characters"),

  body("generatedBy")
    .notEmpty()
    .withMessage("Generated by is required")
    .isMongoId()
    .withMessage("Invalid Admin ID"),

  body("reportDate")
    .notEmpty()
    .withMessage("Report date is required")
    .isISO8601()
    .withMessage("Invalid report date format"),

  body("reportFile")
    .trim()
    .notEmpty()
    .withMessage("Report file is required")
    .isLength({ min: 1, max: 500 })
    .withMessage("Report file path must not exceed 500 characters"),
];

const updateReportValidation = [
  body("reportType")
    .optional()
    .trim()
    .isLength({ min: 3, max: 100 })
    .withMessage("Report type must be between 3 and 100 characters"),

  body("generatedBy")
    .optional()
    .isMongoId()
    .withMessage("Invalid Admin ID"),

  body("reportDate")
    .optional()
    .isISO8601()
    .withMessage("Invalid report date format"),

  body("reportFile")
    .optional()
    .trim()
    .isLength({ min: 1, max: 500 })
    .withMessage("Report file path must not exceed 500 characters"),
];

export {
  createReportValidation,
  updateReportValidation,
};
